# -*- coding: utf-8 -*-
"""
`group_option_figures`：哪几张插图是选项配图（A/B/C/D 各一张）。

判据全是几何的。认错的后果不是报错：选项文本为空又没配图 → `text_quality` 判
degraded → 页面上选项全空、图无标号挂在题干下面，读题的人分不出哪张是哪个选项；
③ 解题只拿到「题干插图1..4」没有字母，只能靠数数猜对应，**错位就是整道题全错
且静默**（真题 PDF 没参考答案对不了账，④b 只检 spec 自洽、⑥ 只检动画，
全链路没有一层看选项字母）。

坐标约定：`x` 是左边，**`y` 是底边**（PDF 原点在左下），`w`/`h` 是宽高。
顶边 = `y + h`。

下面每一条都对着 `work/` 下 24 份卷子的真实几何写，常数后面注的是实测余量。
"""
import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), "pipeline"))
from segment import group_option_figures as gof


def fig(name, x, top, w, h, page=1):
    """按**顶边**给，跟卷子上看到的一致；内部存的是底边。"""
    return {"file": "img/%s.png" % name, "page": page,
            "x": x, "y": top - h, "w": w, "h": h}


def files(fs):
    return [f["file"].split("/")[-1][:-4] for f in fs]


# ── 真实版式 ────────────────────────────────────────────────────────────

def test_一行四个_是最常见的版式():
    """浙江 q3、福建 q4 都是这样。现规则也认得，不能改坏。"""
    row = [fig("a", 76.5, 228.6, 95.2, 96), fig("b", 191.2, 228.6, 99.8, 99.8),
           fig("c", 306.8, 228.6, 99, 96), fig("d", 422.2, 228.6, 98.2, 99)]
    stem, opt = gof(row, 4)
    assert files(opt) == ["a", "b", "c", "d"] and stem == []


def test_二乘二网格_行优先():
    """
    陕西 q1 的真实坐标。**顺序决定图挂给哪个字母** —— 卷面上
    A.(x=61,y=644) B.(x=290,y=644) C.(x=61,y=557) D.(x=290,y=557)，是行优先。
    """
    g = [fig("a", 76.5, 656.9, 96, 79.5), fig("b", 305.2, 656.9, 76.5, 79.5),
         fig("c", 76.5, 569.9, 78.8, 74.2), fig("d", 306, 569.9, 81, 72)]
    stem, opt = gof(list(reversed(g)), 4)      # 输入顺序打乱也要排对
    assert files(opt) == ["a", "b", "c", "d"]


def test_题干图排在网格上方_要被排除():
    """陕西 q8：一张 y-t 振动图像 + 四张 y-x 波形图。"""
    figs = [fig("stem", 60.8, 435.6, 177.8, 137.2),
            fig("a", 76.5, 294.6, 126, 96), fig("b", 305.2, 294.6, 102, 78),
            fig("c", 76.5, 191.1, 116.2, 89.2), fig("d", 306, 191.1, 101.2, 78)]
    stem, opt = gof(figs, 4)
    assert files(opt) == ["a", "b", "c", "d"]
    assert files(stem) == ["stem"]


def test_同一行顶边齐而底边不齐():
    """
    **这是旧规则真正栽的地方。** 陕西 q8 那两张并排图底边差 18pt，
    按 `round(y/12)` 分桶会被劈到两行；顶边却完全相同（实测同行顶边极差恒为 0）。
    """
    figs = [fig("a", 76.5, 294.6, 126, 96), fig("b", 305.2, 294.6, 102, 78),
            fig("c", 76.5, 191.1, 116.2, 89.2), fig("d", 306, 191.1, 101.2, 78)]
    assert files(gof(figs, 4)[1]) == ["a", "b", "c", "d"]


def test_四个选项里有一个明显更宽也要认():
    """
    江苏 q5：A 是阻尼振荡曲线（152pt 宽），其余是直线图（94pt）——
    宽度极差 38.4%。物理内容不同导致长宽比差一倍，这是真实版式，
    不是排版错误。旧的 25% 容差会**误拒一道真题**。
    """
    figs = [fig("stem", 60.75, 513.63, 126, 75.75),
            fig("a", 76.5, 434.13, 152.25, 83.25), fig("b", 305.25, 434.13, 93.75, 103.5),
            fig("c", 76.5, 323.13, 94.5, 105.75), fig("d", 306, 323.13, 94.5, 105.75)]
    stem, opt = gof(figs, 4)
    assert files(opt) == ["a", "b", "c", "d"]
    assert files(stem) == ["stem"]


# ── 该拒的要拒 ──────────────────────────────────────────────────────────

def test_两行离得太远不算一块网格():
    """
    **对抗测试抓到的。** 只查行内对齐、不查行间距的话，陕西 q1 的下半行 +
    陕西 q3 的选项行（相距 267pt、分属两道题）会被凑成一块「2×2 网格」。
    实测真网格的行间空隙全是 7.5pt，加这条上界有十倍余量。
    """
    figs = [fig("a", 76.5, 569.9, 78.8, 74.2), fig("b", 306, 569.9, 81, 72),
            fig("c", 76.5, 228.6, 95.2, 96), fig("d", 306.8, 228.6, 99, 96)]
    assert gof(figs, 4)[1] == []


def test_每行张数不齐不算网格():
    """3+1 不是网格。"""
    figs = [fig("a", 76.5, 228.6, 95, 96), fig("b", 191, 228.6, 95, 96),
            fig("c", 306, 228.6, 95, 96), fig("d", 76.5, 120, 95, 96)]
    assert gof(figs, 4)[1] == []


def test_两行之间列没对齐不算网格():
    figs = [fig("a", 76.5, 228.6, 95, 96), fig("b", 306, 228.6, 95, 96),
            fig("c", 150, 124.6, 95, 96), fig("d", 380, 124.6, 95, 96)]
    assert gof(figs, 4)[1] == []


def test_尺寸差太多不算():
    figs = [fig("a", 76.5, 228.6, 95, 96), fig("b", 191, 228.6, 300, 96),
            fig("c", 76.5, 124.6, 95, 96), fig("d", 191, 124.6, 95, 96)]
    assert gof(figs, 4)[1] == []


def test_跨页不算一块网格():
    figs = [fig("a", 76.5, 228.6, 95, 96, page=1), fig("b", 306, 228.6, 95, 96, page=1),
            fig("c", 76.5, 700, 95, 96, page=2), fig("d", 306, 700, 95, 96, page=2)]
    assert gof(figs, 4)[1] == []


def test_每行只有一张的竖排不认():
    """
    和「题干有 N 张竖排图」在几何上分不开，宁可漏不可错。
    实测全库 12 道非选择题多图题的行结构清一色是 [1,1] 或 [1,1,1]。
    """
    figs = [fig(c, 76.5, 600 - i * 110, 95, 96) for i, c in enumerate("abcd")]
    assert gof(figs, 4)[1] == []


def test_零尺寸的图不许进网格():
    """
    旧规则那句 `if f["w"]` 顺手挡住了 0（falsy）。改写时容易漏掉，
    而 `max(ws)-min(ws) > 0.25*max(ws)` 在全 0 时是 `0 > 0` = 假，一路放行。
    """
    figs = [fig(c, 76.5 + i * 115, 228.6, 0, 0) for i, c in enumerate("abcd")]
    assert gof(figs, 4)[1] == []


def test_坐标缺失的图当不存在():
    figs = [fig("a", 76.5, 228.6, 95, 96), fig("b", 191, 228.6, 95, 96),
            fig("c", 306, 228.6, 95, 96), fig("d", 422, 228.6, 95, 96)]
    figs.insert(0, {"file": "img/none.png", "page": 1,
                    "x": None, "y": None, "w": None, "h": None})
    stem, opt = gof(figs, 4)
    assert files(opt) == ["a", "b", "c", "d"]
    assert files(stem) == ["none"]        # 排除出去，但不能弄丢


# ── 闸门与退化 ──────────────────────────────────────────────────────────

def test_图比选项少直接不判():
    assert gof([fig("a", 76.5, 228.6, 95, 96)], 4) == ([fig("a", 76.5, 228.6, 95, 96)], [])


def test_选项少于两个不判():
    figs = [fig("a", 76.5, 228.6, 95, 96), fig("b", 191, 228.6, 95, 96)]
    assert gof(figs, 1)[1] == []
    assert gof(figs, 0)[1] == []


def test_没有图不崩():
    assert gof([], 4) == ([], [])


def test_网格下方多出一张图_仍然认得出():
    """
    **对抗测试抓到的回归。** 只认「最后一块」的话，网格下方漏进任何一张图
    （下一题的图、页脚图）就从 4 张退回 0 张 —— 比旧规则还差。
    而 `segment.py` 的注释记录过这管线真出过图片超范围归属
    （「实测导致 18 张变 25 张、出现重复归属」）。所以要滑窗，不能钉死末尾。
    """
    figs = [fig("a", 76.5, 228.6, 95, 96), fig("b", 191, 228.6, 99, 96),
            fig("c", 306, 228.6, 99, 96), fig("d", 422, 228.6, 98, 96),
            fig("intruder", 60.75, 100, 140, 80)]
    stem, opt = gof(figs, 4)
    assert files(opt) == ["a", "b", "c", "d"]
    assert files(stem) == ["intruder"]


def test_有两块都像网格时取靠后那块():
    """选项印在题干之后，所以靠后那块才是选项。"""
    figs = [fig("s1", 76.5, 700, 95, 96), fig("s2", 306, 700, 95, 96),
            fig("s3", 76.5, 596, 95, 96), fig("s4", 306, 596, 95, 96),
            fig("a", 76.5, 400, 95, 96), fig("b", 306, 400, 95, 96),
            fig("c", 76.5, 296, 95, 96), fig("d", 306, 296, 95, 96)]
    stem, opt = gof(figs, 4)
    assert files(opt) == ["a", "b", "c", "d"]
    assert files(stem) == ["s1", "s2", "s3", "s4"]


def test_剩下的图保持输入顺序():
    """题干图的顺序决定下游「题干插图1..N」的编号，不能被打乱。"""
    figs = [fig("s1", 60.75, 700, 140, 80), fig("s2", 60.75, 600, 140, 80),
            fig("a", 76.5, 400, 95, 96), fig("b", 191, 400, 95, 96),
            fig("c", 306, 400, 95, 96), fig("d", 422, 400, 95, 96)]
    stem, _ = gof(figs, 4)
    assert files(stem) == ["s1", "s2"]
